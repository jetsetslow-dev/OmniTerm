#!/usr/bin/env python3
"""Generates the terminal's table of double-width characters from the Unicode Character Database.

A character is two cells wide when Unicode gives it East_Asian_Width W or F (UAX #11), or marks it
Emoji_Presentation (UTS #51) other than a regional indicator, or it is an unassigned code point in
one of the blocks UAX #11 says default to W. That is the rule the programs drawing on a terminal use: Ink's string-width (Claude
Code), Rust's unicode-width (Codex, ratatui), and tmux and glibc's wcwidth for East Asian text. The
terminal and the program must agree on every width, or each later redraw on that row lands in the
wrong columns.

The data files are pinned to one Unicode version and checked against their SHA-256 before use.
Moving to a newer version means changing UNICODE_VERSION and both checksums together.

Usage:
  python3 -I scripts/generate-unicode-width.py [--ucd-dir DIR]          write the table
  python3 -I scripts/generate-unicode-width.py --check [--ucd-dir DIR]  fail if the table is stale

Without --ucd-dir the files are downloaded from unicode.org into a temporary directory.
"""
import argparse
import hashlib
import pathlib
import sys
import tempfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "app/src/main/java/com/jetsetslow/omniterm/data/term/UnicodeWidthTable.kt"

UNICODE_VERSION = "16.0.0"
FILES = {
    "EastAsianWidth.txt": (
        f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/EastAsianWidth.txt",
        "43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b",
    ),
    "emoji-data.txt": (
        f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/emoji/emoji-data.txt",
        "f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a",
    ),
}

# UAX #11: unassigned code points in these ranges default to W (EastAsianWidth.txt header).
DEFAULT_WIDE = [
    (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF),
    (0xF900, 0xFAFF),
    (0x20000, 0x2FFFD),
    (0x30000, 0x3FFFD),
]


def fetch(directory: pathlib.Path, name: str) -> pathlib.Path:
    url, expected = FILES[name]
    path = directory / name
    if not path.exists():
        with urllib.request.urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != expected:
        sys.exit(f"{name}: SHA-256 {actual} is not the pinned {expected}")
    return path


def property_ranges(path: pathlib.Path, wanted):
    """(first, last) for every line of a UCD property file whose value is in [wanted]."""
    for line in path.read_text(encoding="utf-8").splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        points, value = (part.strip() for part in data.split(";")[:2])
        if value not in wanted:
            continue
        first, _, last = points.partition("..")
        yield int(first, 16), int(last or first, 16)


# Regional indicators are Emoji_Presentation but East_Asian_Width N: one alone is one cell, as in
# string-width, unicode-width and wcwidth. The emulator joins a pair into a two-cell flag itself.
REGIONAL_INDICATORS = (0x1F1E6, 0x1F1FF)


def without(ranges, hole):
    for first, last in ranges:
        if last < hole[0] or first > hole[1]:
            yield first, last
            continue
        if first < hole[0]:
            yield first, hole[0] - 1
        if last > hole[1]:
            yield hole[1] + 1, last


def merge(ranges):
    merged = []
    for first, last in sorted(ranges):
        if merged and first <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], last)
        else:
            merged.append([first, last])
    return merged


def render(ranges) -> str:
    lines = [
        "// Generated by scripts/generate-unicode-width.py from Unicode "
        f"{UNICODE_VERSION}. Do not edit by hand.",
        "// Unicode data: Copyright (c) 1991-2024 Unicode, Inc., under the Unicode License v3; see NOTICE.md.",
        "package com.jetsetslow.omniterm.data.term",
        "",
        "/**",
        " * Characters a terminal draws two cells wide: East_Asian_Width W or F, Emoji_Presentation, and the",
        " * unassigned code points UAX #11 defaults to W. Pairs of first and last code point, sorted.",
        " */",
        "internal object UnicodeWidthTable {",
        f"    const val UNICODE_VERSION = \"{UNICODE_VERSION}\"",
        "",
        "    private val WIDE = intArrayOf(",
    ]
    for first, last in ranges:
        lines.append(f"        0x{first:X}, 0x{last:X},")
    lines += [
        "    )",
        "",
        "    fun isWide(codePoint: Int): Boolean {",
        "        var low = 0",
        "        var high = WIDE.size / 2 - 1",
        "        while (low <= high) {",
        "            val mid = (low + high) ushr 1",
        "            when {",
        "                codePoint < WIDE[mid * 2] -> high = mid - 1",
        "                codePoint > WIDE[mid * 2 + 1] -> low = mid + 1",
        "                else -> return true",
        "            }",
        "        }",
        "        return false",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd-dir", type=pathlib.Path, help="directory holding the pinned files")
    parser.add_argument("--check", action="store_true", help="fail if the committed table differs")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as scratch:
        directory = args.ucd_dir or pathlib.Path(scratch)
        width = fetch(directory, "EastAsianWidth.txt")
        emoji = fetch(directory, "emoji-data.txt")
        ranges = list(property_ranges(width, {"W", "F"}))
        ranges += property_ranges(emoji, {"Emoji_Presentation"})
        ranges += DEFAULT_WIDE
        table = merge(without(ranges, REGIONAL_INDICATORS))
        text = render(table)

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run scripts/generate-unicode-width.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} matches Unicode {UNICODE_VERSION}")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(table)} ranges, Unicode {UNICODE_VERSION})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
